/**
 * pullFromServer(서버 → 로컬)와 pushToServer(로컬 큐 → 서버)의 순서를 세운다.
 *
 * 왜 필요한가:
 * 둘은 같은 데이터를 반대 방향으로 옮기는데, 서로의 중간 상태를 보면
 * 사용자의 변경이 사라진다. 대표적으로 —
 *
 *   1. 사용자가 습관 삭제 → 로컬에서 지워지고 큐에 DELETE 적재
 *   2. pull이 서버에 목록 요청 (아직 응답 전)
 *   3. push가 서버 삭제를 끝내고 큐를 비움
 *   4. pull에 2번 시점의 응답 도착 — 삭제된 습관이 아직 들어있음
 *   5. 큐가 비어 있으니 보호 대상 없음 → 삭제한 습관이 되살아남
 *
 * 큐가 비었다는 게 "보낼 게 없었다"인지 "방금 다 보냈다"인지 pull은
 * 구분할 수 없다. 그래서 큐 상태로 판별하는 대신 아예 겹치지 않게 만든다.
 *
 * 핵심은 pull의 **서버 조회까지** 이 잠금 안에 넣는 것이다. 조회를 밖에
 * 두면 잠금을 잡았을 땐 이미 낡은 응답을 들고 있게 되어 의미가 없다.
 * (Dexie 트랜잭션과는 별개다. 트랜잭션 안에서는 네트워크를 기다릴 수 없으므로
 *  이 잠금이 조회 + 트랜잭션을 함께 감싸는 바깥 울타리 역할을 한다.)
 */
let tail: Promise<unknown> = Promise.resolve();

export function withSyncLock<T>(fn: () => Promise<T>): Promise<T> {
  // 앞 작업의 성공/실패와 무관하게 다음 작업을 실행한다.
  const run = tail.then(fn, fn);
  // 체인에는 처리된 형태로만 남긴다. 그러지 않으면 한 번의 실패가
  // 미처리 rejection으로 새어 나가고 뒤 작업까지 연쇄로 끊긴다.
  tail = run.catch(() => {});
  return run;
}
